// Writes THIRD_PARTY_LICENSES.md: the npm packages bundled into the app, the Rust crates built into the core for
// macOS, and Electron itself, each with its license text. Identical texts are printed once with the packages using them.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const output = resolve(root, "THIRD_PARTY_LICENSES.md");
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/iu;

function licenseTexts(directory) {
  if (!directory || !existsSync(directory)) return [];
  // Files only: some crates keep a LICENSES/ directory beside their license files.
  return readdirSync(directory, { withFileTypes: true }).filter(entry => entry.isFile() && LICENSE_FILE.test(entry.name)).map(entry => entry.name).sort()
    .map(name => readFileSync(join(directory, name), "utf8").replace(/\r\n/gu, "\n").trim())
    .filter(Boolean);
}

/** @type {{ name: string; version: string; license: string; source: "npm" | "cargo"; texts: string[] }[]} */
const packages = [];

// npm: production dependencies of the workspace (what the renderer and main bundles contain).
// Walk `pnpm -r list --prod` directly from local node_modules so pruned global pnpm store index files never break release builds.
const seenNpm = new Set();
function collectNpmDeps(deps) {
  if (!deps || typeof deps !== "object") return;
  for (const entry of Object.values(deps)) {
    if (!entry || typeof entry !== "object") continue;
    const { from, version, path: pkgPath, dependencies } = entry;
    if (typeof version === "string" && !version.startsWith("link:") && typeof pkgPath === "string") {
      const name = typeof from === "string" && from.length > 0 ? from : JSON.parse(readFileSync(join(pkgPath, "package.json"), "utf8")).name;
      const key = `${name}@${version}`;
      if (!seenNpm.has(key)) {
        seenNpm.add(key);
        const manifest = existsSync(join(pkgPath, "package.json")) ? JSON.parse(readFileSync(join(pkgPath, "package.json"), "utf8")) : {};
        const declared = typeof manifest.license === "string"
          ? manifest.license
          : (manifest.license && typeof manifest.license === "object" && typeof manifest.license.type === "string" ? manifest.license.type : "UNKNOWN");
        packages.push({ name, version, license: declared, source: "npm", texts: licenseTexts(pkgPath) });
      }
    }
    collectNpmDeps(dependencies);
  }
}
const workspaceList = JSON.parse(execFileSync("pnpm", ["-r", "list", "--prod", "--depth", "Infinity", "--json"], { cwd: root, encoding: "utf8", maxBuffer: 64 << 20 }));
for (const project of workspaceList) collectNpmDeps(project.dependencies);
// Electron is a build dependency but ships inside the app.
const electronDir = dirname(execFileSync(process.execPath, ["-p", "require.resolve('electron/package.json')"], { cwd: root, encoding: "utf8" }).trim());
const electron = JSON.parse(readFileSync(join(electronDir, "package.json"), "utf8"));
packages.push({ name: "electron", version: electron.version, license: electron.license ?? "MIT", source: "npm", texts: licenseTexts(electronDir) });

// Cargo: crates resolved for the macOS (Apple silicon) build of the core.
const cargo = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", "aarch64-apple-darwin"],
  { cwd: root, encoding: "utf8", maxBuffer: 64 << 20 }));
const used = new Set(cargo.resolve.nodes.map(node => node.id));
for (const crate of cargo.packages) {
  if (crate.source === null || !used.has(crate.id)) continue;
  packages.push({ name: crate.name, version: crate.version, license: crate.license ?? crate.license_file ?? "UNKNOWN", source: "cargo",
    texts: licenseTexts(dirname(crate.manifest_path)) });
}

packages.sort((a, b) => a.source.localeCompare(b.source) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const byText = new Map();
for (const item of packages) {
  for (const text of item.texts) {
    const users = byText.get(text) ?? [];
    users.push(`${item.name} ${item.version}`);
    byText.set(text, users);
  }
}
const missing = packages.filter(item => item.texts.length === 0);

const lines = [
  "# Third-party licenses",
  "",
  "CherryPeek includes the following third-party software. This file is generated by `pnpm licenses:third-party`; do not edit it by hand.",
  "",
  `${packages.filter(item => item.source === "npm").length} npm packages (bundled into the app, including Electron) and ${packages.filter(item => item.source === "cargo").length} Rust crates (built into the core).`,
  "",
  "| Package | Version | License | Source |",
  "| --- | --- | --- | --- |",
  ...packages.map(item => `| ${item.name} | ${item.version} | ${item.license} | ${item.source} |`),
  "",
];
if (missing.length) {
  lines.push("Packages that ship no license file; their declared license applies:", "",
    ...missing.map(item => `- ${item.name} ${item.version} (${item.license})`), "");
}
lines.push("## License texts", "");
for (const [text, users] of byText) {
  lines.push(`### ${users.join(", ")}`, "", "```text", text.replace(/```/gu, "'''"), "```", "");
}
writeFileSync(output, `${lines.join("\n").trimEnd()}\n`);
console.log(`Wrote ${output}: ${packages.length} packages, ${byText.size} distinct license texts, ${missing.length} without a license file.`);
